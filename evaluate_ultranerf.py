def subsample_poses_depth(poses, subsample_every_n, full_volume_mode=True):
    """
    Subsample poses in the depth dimension for 3D interpolation.
    
    Args:
        poses: Pose array [N, D, 3, 4] or [N, 3, 4]
        subsample_every_n: Keep every n-th pose in depth dimension (1 = keep all)
        full_volume_mode: Whether using 3D volume mode
    
    Returns:
        subsampled_poses: Subsampled pose array
        kept_indices: Indices of kept poses in original array
        mapping_info: Dictionary with reconstruction metadata
    """
    if not full_volume_mode or subsample_every_n == 1:
        # No subsampling needed
        if poses.ndim == 3:
            # [N, 3, 4] - 2D mode
            all_indices = np.arange(poses.shape[0])
        else:
            # [N, D, 3, 4] - 3D mode but keeping all
            all_indices = np.arange(poses.shape[1])
        
        return poses, all_indices, {
            'subsample_every_n': 1,
            'original_depth': poses.shape[1] if poses.ndim == 4 else poses.shape[0],
            'subsampled_depth': poses.shape[1] if poses.ndim == 4 else poses.shape[0],
            'kept_indices': all_indices
        }
    
    # Full volume mode with subsampling
    assert poses.ndim == 4, f"Expected poses shape [N, D, 3, 4] for full_volume_mode, got {poses.shape}"
    
    N, D, _, _ = poses.shape
    
    # Generate subsampling indices
    kept_indices = np.arange(0, D, subsample_every_n)
    
    # Ensure we always keep the last pose for complete coverage
    if kept_indices[-1] != D - 1:
        kept_indices = np.append(kept_indices, D - 1)
    
    # Subsample
    subsampled_poses = poses[:, kept_indices, :, :]
    
    mapping_info = {
        'subsample_every_n': subsample_every_n,
        'original_depth': D,
        'subsampled_depth': len(kept_indices),
        'kept_indices': kept_indices,
        'volumes_processed': N
    }
    
    print(f"\nSubsampling Info:")
    print(f"  Original depth: {D}")
    print(f"  Subsample every: {subsample_every_n}")
    print(f"  Subsampled depth: {len(kept_indices)}")
    print(f"  Kept indices: {kept_indices}")
    print(f"  Compression ratio: {len(kept_indices)/D:.2%}")
    
    return subsampled_poses, kept_indices, mapping_info

