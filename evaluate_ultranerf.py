def get_target(images, img_i, pts_image):
    """ Loads the image as a tensor by its index.
        For convex mode it remaps original image to reflect only points
        along sampling rays according to sampling points (pts_image).
        Sampling points are generated by calling calc_image_sampling_points_convex() method.
        If cache is enabled, it loads from cache."""
    global cached_images
    if not convex.config['use_convex_mode']:
        return images[img_i].transpose(0, 1)  # equivalent to tf.transpose(images[img_i])
    else:
        if convex.config['convex_use_compiled_cache']:
            if cached_images[img_i] is not None:
                out = cached_images[img_i]
            else:
                out = remap_target_for_comparison(images[img_i], pts_image)
                cached_images[img_i] = out
        else:
            out = remap_target_for_comparison(images[img_i], pts_image)

        return out

def visualize_2d_slice(rendering_output, pts_image, W, H, output_path, img_i, mode="eval"):
    """Visualize 2D slice rendering outputs (no target comparison)."""
    plt.figure(figsize=(16, 9))
    
    for j, m in enumerate(list(rendering_output.keys())[:12]):
        plt.subplot(3, 4, j + 1)
        plt.title(m)
        array = rendering_output[m].detach().cpu().numpy()[0, 0].T
        if convex.config['use_convex_mode']:
            array = remap_output_to_original_image(array.T, pts_image, W, H)
        plt.imshow(array)

    plt.savefig(
        os.path.join(output_path, "{}_{}.png".format(mode, img_i)),
        bbox_inches="tight",
        dpi=200,
    )
    plt.close()


def visualize_3d_volume_slices(rendering_output, output_image, pts_image, W, H, D, 
                                output_path, img_i, mode="eval", n_slices=3, 
                                save_volume=True, target_volume=None, nerf_original_vis=True):
    """Visualize random slices from 3D volume and optionally save the full volume."""
    
    # Select random slices to visualize
    indices = random.sample(range(D), min(n_slices, D))
    
    for k in indices:
        plt.figure(figsize=(16, 9))
        
        for j, m in enumerate(list(rendering_output.keys())[:12]):
            plt.subplot(3, 4, j + 1)
            if j == 11 and target_volume is not None:
                plt.title("Target")
                array = target_volume[k]
            else:
                plt.title(m)
                array = rendering_output[m].detach().cpu().numpy()[0, k]
                if convex.config['use_convex_mode'] and nerf_original_vis:
                    array = remap_output_to_original_image(array, pts_image, W, H, 
                                                        _interpolate=1)#, interpolation_method="nearest")
            plt.imshow(array)

        plt.savefig(
            os.path.join(output_path, "{}_{}_{}.png".format(k, mode, img_i)),
            bbox_inches="tight",
            dpi=200,
        )
        plt.close()
    
    # Save full 3D volume if requested
    if save_volume:
        slices = []
        
        for d in range(D):
            array = output_image.detach().cpu().numpy()[0, d]
            if nerf_original_vis:
                slices.append(remap_output_to_original_image(array, pts_image, W, H, _interpolate=1))#, interpolation_method="nearest"))
            else:
                slices.append(array)
        output_volume = np.stack(slices, axis=0)
        #print(f"Output volume min: {output_volume.min()}, max: {output_volume.max()}")
        print(f"Output volume min: {output_volume.min()}, max: {output_volume.max()}")
        # Normalize to [0, 1]
        output_volume = (output_volume - output_volume.min()) / (output_volume.max() - output_volume.min())
